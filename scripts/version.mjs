import { readFile, writeFile } from "node:fs/promises";

const packageJson = JSON.parse(
  await readFile(new URL("../package.json", import.meta.url), "utf8"),
);
const target = new URL("../src/version.ts", import.meta.url);
const contents = `// Generated by scripts/version.mjs. Do not edit manually.\nexport const SDK_NAME = ${JSON.stringify(packageJson.name)};\nexport const SDK_VERSION = ${JSON.stringify(packageJson.version)};\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== contents) {
    console.error("src/version.ts is out of date. Run: pnpm version:sync");
    process.exitCode = 1;
  }
} else {
  await writeFile(target, contents);
}
